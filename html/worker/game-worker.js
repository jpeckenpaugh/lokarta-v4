const OPTIONS_KEY = 'options';
const LAST_PLAYED_KEY = 'last_played_slot';

/**
 * True when the cached floor was generated by the current dungeon template;
 * false for floors baked by older templates (e.g. the legacy thick-walled
 * layout) that must be regenerated instead of replayed from IndexedDB.
 * @param {object|null} floor
 * @returns {boolean}
 */
export function isStaleFloor(floor, towerId = null) {
  if (!floor) return true;
  if (floor.template_version !== FLOOR_TEMPLATE_VERSION) return true;
  // A cached floor belongs to exactly one tower: switching towers regenerates
  // and overwrites the slot's floor cache without an IndexedDB schema change.
  // A legacy record with no tower id is treated as the default tower.
  if (towerId && (floor.tower_id || DEFAULT_TOWER_ID) !== towerId) return true;
  return false;
}

/** Resolves a requested tower id to an authored tower id (falls back to default). */
function resolveTowerId(towerId) {
  const tower = getTowerDefinition(towerId);
  return tower ? tower.id : DEFAULT_TOWER_ID;
}

function clampFloor(value, towerId = DEFAULT_TOWER_ID) {
  return clampTowerFloor(value, towerId);
}

function clampSlotIndex(value) {
  const n = Math.floor(Number(value));
  if (!Number.isFinite(n) || n < 1 || n > SAVE_SLOT_COUNT) {
    throw new Error(`Invalid save slot index: ${value}`);
  }
  return n;
}

async function ensureProfile(soundEnabled = true) {
  let profile = await read(STORES.PROFILE, 'default_profile');
  if (!profile) {
    profile = {
      id: 'default_profile',
      soundEnabled,
      volume: 0.7,
      createdAt: now(),
      updatedAt: now(),
    };
    await put(STORES.PROFILE, profile);
  }
  return profile;
}

async function readOptionsRecord() {
  const record = await read(STORES.GAME_SETTINGS, OPTIONS_KEY);
  return normalizeOptions(record ? record.options : null);
}

async function persistOptions(options) {
  const profile = await ensureProfile(Boolean(options.soundEffects));
  profile.soundEnabled = Boolean(options.soundEffects);
  profile.updatedAt = now();
  await put(STORES.PROFILE, profile);
  await put(STORES.GAME_SETTINGS, {
    key: OPTIONS_KEY,
    version: 1,
    options,
    updatedAt: now(),
  });
  return options;
}

async function writeLastPlayed(slotIndex) {
  await put(STORES.GAME_SETTINGS, { key: LAST_PLAYED_KEY, slotIndex, updatedAt: now() });
}

async function readLastPlayed() {
  const record = await read(STORES.GAME_SETTINGS, LAST_PLAYED_KEY);
  return record ? record.slotIndex : null;
}

/**
 * Loads a slot-scoped cached floor or generates and caches a fresh one.
 * @param {number} slotIndex
 * @param {number} floorNumber
 * @param {boolean} [forceRegenerate=false]
 * @returns {Promise<object>}
 */
async function loadOrGenerateSlotFloor(slotIndex, floorNumber, towerId = DEFAULT_TOWER_ID, forceRegenerate = false) {
  const resolvedTowerId = resolveTowerId(towerId);
  const fn = clampFloor(floorNumber, resolvedTowerId);
  let floor = null;
  if (!forceRegenerate) {
    floor = await read(STORES.SLOT_FLOORS, slotFloorKey(slotIndex, fn));
    if (isStaleFloor(floor, resolvedTowerId)) floor = null;
  }
  if (!floor) {
    floor = generateFloor(fn, null, resolvedTowerId);
    floor.slotIndex = slotIndex;
    await put(STORES.SLOT_FLOORS, floor);
  }
  return floor;
}

function makeSlotPlayer(vocation, slotIndex) {
  const player = createPlayer(vocation, `char_slot_${slotIndex}`);
  const timestamp = now();
  player.slotId = slotId(slotIndex);
  player.slotIndex = slotIndex;
  player.saveVersion = SAVE_FORMAT_VERSION;
  player.playtimeMs = 0;
  player.createdAt = timestamp;
  player.updatedAt = timestamp;
  player.lastPlayedAt = timestamp;
  return player;
}

/**
 * Refreshes a slot's metadata from the current player state.
 * @returns {Promise<object|null>} updated slot record or null when unoccupied
 */
async function refreshSlot(slotIndex, player, biome, timestamp) {
  const existing = await read(STORES.SAVE_SLOTS, slotId(slotIndex));
  if (!existing || existing.status !== 'occupied') return null;
  const meta = deriveSlotMeta(player, slotIndex, biome || existing.biome);
  const updated = {
    ...existing,
    ...meta,
    createdAt: existing.createdAt || meta.createdAt || timestamp,
    lastPlayedAt: timestamp || meta.lastPlayedAt,
  };
  await put(STORES.SAVE_SLOTS, updated);
  return updated;
}

/**
 * Bootstraps game storage: profile, options, all save slots, and the last
 * played slot. Runs the v1 -> v2 migration once.
 * @returns {Promise<object>}
 */
async function handleBootstrap() {
  await openStorage();

  const profile = await ensureProfile();

  try {
    await migrateLegacySave();
  } catch (err) {
    console.warn('game-worker: legacy save migration failed; continuing with empty slots.', err);
  }

  // One-time 20 -> 5 tower migration: reset stale floor caches and clamp any
  // pre-tower character/slot onto the 5 levels. Runs after the slot migration
  // so a freshly migrated v1 save is also normalized.
  try {
    await migrateTowerSave();
  } catch (err) {
    console.warn('game-worker: tower save migration failed; saves will clamp on load.', err);
  }

  const options = await readOptionsRecord();
  const slots = await readSlots();
  const lastPlayedSlotIndex = await readLastPlayed();

  // Keep the profile's legacy sound flag in sync with the options model.
  if (profile.soundEnabled !== options.soundEffects) {
    profile.soundEnabled = options.soundEffects;
    profile.updatedAt = now();
    await put(STORES.PROFILE, profile);
  }

  return { profile, options, slots, lastPlayedSlotIndex };
}

/**
 * Returns the five save-slot metadata records.
 * @returns {Promise<{ slots: object[] }>}
 */
async function handleListSlots() {
  await openStorage();
  return { slots: await readSlots() };
}

/**
 * Creates a fresh character in the targeted slot.
 * @param {{ slotIndex: number, vocation?: string }} payload
 * @returns {Promise<{ player: object, floor: object, slot: object }>}
 */
async function handleCreateSlot(payload = {}) {
  const { vocation = 'magician' } = payload;
  const towerId = resolveTowerId(payload.towerId);
  const slotIndex = clampSlotIndex(payload.slotIndex);
  await openStorage();

  const player = makeSlotPlayer(vocation, slotIndex);
  player.towerId = towerId;
  const floor = generateFloor(1, null, towerId);
  floor.slotIndex = slotIndex;
  if (floor.spawn_coords) {
    player.x = floor.spawn_coords.x;
    player.y = floor.spawn_coords.y;
  }
  player.current_floor = 1;
  player.floorEntry = snapshotFloorEntry(player);

  await put(STORES.CHARACTERS, player);
  await put(STORES.SLOT_FLOORS, floor);
  await put(STORES.DUNGEON_FLOORS, floor);

  const slot = deriveSlotMeta(player, slotIndex, floor.biome_name);
  await put(STORES.SAVE_SLOTS, slot);
  await writeLastPlayed(slotIndex);

  return { player, floor, slot };
}

/**
 * Selects a tower for an occupied slot: stamps the tower id, restarts the
 * character at that tower's level 1, regenerates its floor, and persists. Keys
 * and spring charges are per-run and reset so a fresh tower cannot inherit the
 * previous tower's progression.
 * @param {{ slotIndex: number, towerId: string }} payload
 * @returns {Promise<{ player: object, floor: object, slot: object }>}
 */
async function handleSelectTower(payload = {}) {
  const slotIndex = clampSlotIndex(payload.slotIndex);
  const towerId = resolveTowerId(payload.towerId);
  await openStorage();

  const slot = await read(STORES.SAVE_SLOTS, slotId(slotIndex));
  if (!slot || slot.status !== 'occupied' || !slot.characterId) {
    throw new Error(`Slot ${slotIndex} is empty.`);
  }
  const stored = await read(STORES.CHARACTERS, slot.characterId);
  if (!stored) {
    throw new Error(`Could not load Slot ${slotIndex}. Try again.`);
  }

  const player = {
    ...stored,
    towerId,
    current_floor: 1,
    levelKeys: {},
    springCharges: {},
    saveVersion: SAVE_FORMAT_VERSION,
  };
  const floor = generateFloor(1, null, towerId);
  floor.slotIndex = slotIndex;
  const start = floor.spawn_coords || floor.entrance;
  if (start) {
    player.x = start.x;
    player.y = start.y;
  }
  player.slotId = slotId(slotIndex);
  player.slotIndex = slotIndex;
  player.floorEntry = snapshotFloorEntry(player);
  const timestamp = now();
  player.updatedAt = timestamp;
  player.lastPlayedAt = timestamp;

  await put(STORES.CHARACTERS, player);
  await put(STORES.SLOT_FLOORS, floor);
  await put(STORES.DUNGEON_FLOORS, floor);
  const updatedSlot = await refreshSlot(slotIndex, player, floor.biome_name, timestamp);
  await writeLastPlayed(slotIndex);

  return { player, floor, slot: updatedSlot || slot };
}

/**
 * Loads an occupied slot's character and current floor.
 * @param {{ slotIndex: number }} payload
 * @returns {Promise<{ player: object, floor: object, slot: object }>}
 */
async function handleLoadSlot(payload = {}) {
  const slotIndex = clampSlotIndex(payload.slotIndex);
  await openStorage();

  const slot = await read(STORES.SAVE_SLOTS, slotId(slotIndex));
  if (!slot || slot.status !== 'occupied') {
    throw new Error(`Slot ${slotIndex} is empty.`);
  }

  const stored = await read(STORES.CHARACTERS, slot.characterId);
  if (!stored) {
    throw new Error(`Could not load Slot ${slotIndex}. Try again.`);
  }
  // Clamp a pre-tower save (which may point past its tower's final level) onto
  // the selected tower and stamp the current save format before any floor is
  // generated or cached.
  const towerId = resolveTowerId(stored.towerId || slot.towerId);
  const player = {
    ...migratePlayerToTower(stored, towerId),
    towerId,
    saveVersion: SAVE_FORMAT_VERSION,
  };

  const floor = await loadOrGenerateSlotFloor(slotIndex, player.current_floor || 1, towerId);
  // Continuing a save always starts at the level's start position,
  // regardless of where the player stood when last saved.
  const start = floor.spawn_coords || floor.entrance;
  if (start) {
    player.x = start.x;
    player.y = start.y;
  }
  player.floorEntry = snapshotFloorEntry(player);
  player.slotId = slotId(slotIndex);
  player.slotIndex = slotIndex;
  const timestamp = now();
  player.updatedAt = timestamp;
  player.lastPlayedAt = timestamp;

  await put(STORES.CHARACTERS, player);
  const updatedSlot = await refreshSlot(slotIndex, player, floor.biome_name, timestamp);
  await writeLastPlayed(slotIndex);

  return { player, floor, slot: updatedSlot || slot };
}

/**
 * Deletes a slot's character, metadata, and floor cache. Never touches the
 * legacy single-save stores.
 * @param {{ slotIndex: number }} payload
 * @returns {Promise<{ success: boolean }>}
 */
async function handleDeleteSlot(payload = {}) {
  const slotIndex = clampSlotIndex(payload.slotIndex);
  await openStorage();

  const slot = await read(STORES.SAVE_SLOTS, slotId(slotIndex));
  if (slot && slot.characterId) {
    await deleteRecord(STORES.CHARACTERS, slot.characterId);
  }
  await deleteRecord(STORES.SAVE_SLOTS, slotId(slotIndex));

  const floors = await getAll(STORES.SLOT_FLOORS);
  for (const floor of floors || []) {
    if (floor && floor.slotIndex === slotIndex) {
      await deleteRecord(STORES.SLOT_FLOORS, slotFloorKey(floor.slotIndex, floor.floor_number));
    }
  }

  if ((await readLastPlayed()) === slotIndex) {
    await deleteRecord(STORES.GAME_SETTINGS, LAST_PLAYED_KEY);
  }

  return { success: true };
}

/**
 * Restores a slot's floor-entry snapshot so the current floor restarts from
 * its arrival state.
 * @param {{ slotIndex: number }} payload
 * @returns {Promise<{ player: object, floor: object }>}
 */
async function handleRestartFloor(payload = {}) {
  const slotIndex = clampSlotIndex(payload.slotIndex);
  await openStorage();

  const slot = await read(STORES.SAVE_SLOTS, slotId(slotIndex));
  if (!slot || slot.status !== 'occupied' || !slot.characterId) {
    throw new Error(`Slot ${slotIndex} is empty.`);
  }
  const player = await read(STORES.CHARACTERS, slot.characterId);
  if (!player) {
    throw new Error(`Could not load Slot ${slotIndex}. Try again.`);
  }

  const towerId = resolveTowerId(player.towerId || slot.towerId);
  player.towerId = towerId;
  // Clamp the pre-tower snapshot floor before restoring so a legacy floorEntry
  // can never put the player past the tower's final level.
  if (slot.floorEntry) {
    slot.floorEntry = { ...slot.floorEntry, current_floor: clampTowerFloor(slot.floorEntry.current_floor, towerId) };
  }
  restoreFloorEntry(player, slot.floorEntry);
  player.towerId = towerId;
  player.current_floor = clampTowerFloor(player.current_floor, towerId);
  player.slotId = slotId(slotIndex);
  player.slotIndex = slotIndex;
  player.saveVersion = SAVE_FORMAT_VERSION;
  const timestamp = now();
  player.updatedAt = timestamp;
  player.lastPlayedAt = timestamp;

  const floor = await loadOrGenerateSlotFloor(slotIndex, player.current_floor || 1, towerId);
  if (floor.spawn_coords) {
    player.x = player.x ?? floor.spawn_coords.x;
    player.y = player.y ?? floor.spawn_coords.y;
  }
  player.floorEntry = snapshotFloorEntry(player);

  await put(STORES.CHARACTERS, player);
  await refreshSlot(slotIndex, player, floor.biome_name, timestamp);
  await writeLastPlayed(slotIndex);

  return { player, floor };
}

/**
 * Respawns a defeated player one level lower (never below level 1) with full
 * health and mana, landing at that level's start position.
 * @param {{ slotIndex: number }} payload
 * @returns {Promise<{ player: object, floor: object }>}
 */
async function handleRespawnAfterDeath(payload = {}) {
  const slotIndex = clampSlotIndex(payload.slotIndex);
  await openStorage();

  const slot = await read(STORES.SAVE_SLOTS, slotId(slotIndex));
  if (!slot || slot.status !== 'occupied' || !slot.characterId) {
    throw new Error(`Slot ${slotIndex} is empty.`);
  }
  const player = await read(STORES.CHARACTERS, slot.characterId);
  if (!player) {
    throw new Error(`Could not load Slot ${slotIndex}. Try again.`);
  }

  player.towerId = resolveTowerId(player.towerId || slot.towerId);
  const respawnFloor = descendOnDeath(player);
  player.current_floor = respawnFloor;
  applyFullRestore(player);

  const floor = await loadOrGenerateSlotFloor(slotIndex, respawnFloor, player.towerId);
  // Land at the level's start position (its entrance spawn / arrival from below).
  const start = resolveArrivalCoords(floor, respawnFloor - 1) || floor.spawn_coords || floor.entrance;
  if (start) {
    player.x = start.x;
    player.y = start.y;
  }

  player.slotId = slotId(slotIndex);
  player.slotIndex = slotIndex;
  player.saveVersion = SAVE_FORMAT_VERSION;
  player.floorEntry = snapshotFloorEntry(player);
  const timestamp = now();
  player.updatedAt = timestamp;
  player.lastPlayedAt = timestamp;

  await put(STORES.CHARACTERS, player);
  await refreshSlot(slotIndex, player, floor.biome_name, timestamp);
  await writeLastPlayed(slotIndex);

  return { player, floor };
}

/**
 * Legacy single-save new game (kept for backward compatibility).
 * @param {{ vocation?: string }} payload
 * @returns {Promise<{ player: object, floor: object }>}
 */
async function handleNewGame(payload = {}) {
  const { vocation = 'magician' } = payload;
  await openStorage();

  const towerId = resolveTowerId(payload.towerId);
  const player = createPlayer(vocation);
  player.towerId = towerId;
  const currentTime = now();
  player.createdAt = currentTime;
  player.updatedAt = currentTime;
  player.playtimeMs = 0;

  const floor = generateFloor(1, null, towerId);
  if (floor.spawn_coords) {
    player.x = floor.spawn_coords.x;
    player.y = floor.spawn_coords.y;
  }
  player.current_floor = 1;

  await put(STORES.CHARACTERS, player);
  await put(STORES.DUNGEON_FLOORS, floor);

  return { player, floor };
}

/**
 * Commits current player state, updating slot metadata when slot-scoped.
 * @param {{ player: object }} payload
 * @returns {Promise<{ success: boolean, savedAt: string }>}
 */
async function handleSaveCharacter(payload = {}) {
  const { player } = payload;
  if (!player) {
    throw new Error('Missing player object in saveCharacter payload.');
  }

  await openStorage();
  const savedAt = now();
  player.updatedAt = savedAt;
  // Never persist a floor outside the player's tower, whatever the caller sent.
  player.current_floor = clampTowerFloor(player.current_floor, player.towerId);
  player.saveVersion = SAVE_FORMAT_VERSION;

  await put(STORES.CHARACTERS, player);

  if (player.slotIndex) {
    await refreshSlot(player.slotIndex, player, null, player.lastPlayedAt || savedAt);
  }

  return { success: true, savedAt };
}

/**
 * Retrieves a cached floor (slot-scoped when slotIndex is provided) or
 * generates one with generateFloor.
 * @param {{ floorNumber?: number, slotIndex?: number, forceRegenerate?: boolean }} payload
 * @returns {Promise<object>}
 */
async function handleGetFloor(payload = {}) {
  const { floorNumber = 1, slotIndex = null, forceRegenerate = false } = payload;
  const towerId = resolveTowerId(payload.towerId);
  await openStorage();

  if (slotIndex) {
    return loadOrGenerateSlotFloor(clampSlotIndex(slotIndex), floorNumber, towerId, forceRegenerate);
  }

  const fn = clampFloor(floorNumber, towerId);
  let floor = null;
  if (!forceRegenerate) {
    floor = await read(STORES.DUNGEON_FLOORS, fn);
    if (isStaleFloor(floor, towerId)) floor = null;
  }
  if (!floor) {
    floor = generateFloor(fn, null, towerId);
    await put(STORES.DUNGEON_FLOORS, floor);
  }
  return floor;
}

/**
 * Advances a player to the next floor, writing the arrival snapshot into
 * `floorEntry` and the slot metadata.
 * @param {{ player: object, nextFloorNumber?: number }} payload
 * @returns {Promise<{ player: object, floor: object }>}
 */
async function handleAdvanceFloor(payload = {}) {
  const { player, nextFloorNumber } = payload;
  if (!player) {
    throw new Error('Missing player object in advanceFloor payload.');
  }

  await openStorage();

  const towerId = resolveTowerId(player.towerId);
  player.towerId = towerId;
  const currentFloor = Number(player.current_floor) || 1;
  const nextFloor = clampFloor(nextFloorNumber !== undefined ? nextFloorNumber : currentFloor + 1, towerId);
  const slotIndex = player.slotIndex || null;

  let floor;
  if (slotIndex) {
    floor = await loadOrGenerateSlotFloor(slotIndex, nextFloor, towerId);
  } else {
    floor = await read(STORES.DUNGEON_FLOORS, nextFloor);
    if (isStaleFloor(floor, towerId)) {
      floor = generateFloor(nextFloor, null, towerId);
      await put(STORES.DUNGEON_FLOORS, floor);
    }
  }

  player.current_floor = nextFloor;
  player.saveVersion = SAVE_FORMAT_VERSION;
  // Land on the target level's connecting stair (the "exit" seen from the level
  // left behind), not its entrance: from a lower level arrive at the up-stair,
  // from a higher level arrive at the down-stair (D2 §3).
  const arrival = resolveArrivalCoords(floor, currentFloor);
  if (arrival) {
    player.x = arrival.x;
    player.y = arrival.y;
  }
  player.floorEntry = snapshotFloorEntry(player);
  const timestamp = now();
  player.updatedAt = timestamp;
  player.lastPlayedAt = timestamp;

  await put(STORES.CHARACTERS, player);
  if (slotIndex) {
    await put(STORES.DUNGEON_FLOORS, floor);
    await refreshSlot(slotIndex, player, floor.biome_name, timestamp);
  }

  return { player, floor };
}

async function handleGetOptions() {
  await openStorage();
  return { options: await readOptionsRecord() };
}

/**
 * Merges an options patch over the persisted options, normalizes, and stores.
 * @param {{ patch?: object }} payload
 * @returns {Promise<{ options: object }>}
 */
async function handleSetOptions(payload = {}) {
  await openStorage();
  const base = await readOptionsRecord();
  const options = normalizeOptions({ ...base, ...(payload.patch || {}) });
  await persistOptions(options);
  return { options };
}

async function handleResetOptions() {
  await openStorage();
  const options = normalizeOptions(OPTION_DEFAULTS);
  await persistOptions(options);
  return { options };
}

/**
 * Legacy alias for `setOptions({ soundEffects })`.
 * @param {{ soundEnabled: boolean }} payload
 * @returns {Promise<{ options: object }>}
 */
async function handleSetSoundEnabled(payload = {}) {
  await openStorage();
  const base = await readOptionsRecord();
  const options = normalizeOptions({ ...base, soundEffects: Boolean(payload.soundEnabled) });
  await persistOptions(options);
  return { options };
}

/**
 * Clears characters and cached dungeon floors for a clean restart.
 * @returns {Promise<{ success: boolean }>}
 */
async function handleResetProgress() {
  await openStorage();

  await clearStore(STORES.CHARACTERS);
  await clearStore(STORES.DUNGEON_FLOORS);
  await clearStore(STORES.SAVE_SLOTS);
  await clearStore(STORES.SLOT_FLOORS);
  await deleteRecord(STORES.GAME_SETTINGS, MIGRATION_GUARD_KEY);
  await deleteRecord(STORES.GAME_SETTINGS, TOWER_MIGRATION_GUARD_KEY);
  await deleteRecord(STORES.GAME_SETTINGS, LAST_PLAYED_KEY);

  return { success: true };
}

/**
 * Persists chest opened-state for the player's current floor back into the
 * slot floor cache, so re-entering a level keeps opened chests empty. Accepts
 * the minimal chest-state records (see ChestSystem.serializeChestState) and
 * merges them onto the cached floor without touching tiles/entities.
 * @param {{ player?: object, chests?: object[] }} payload
 * @returns {Promise<{ success: boolean }>}
 */
async function handleSaveFloorState(payload = {}) {
  const { player, chests } = payload;
  if (!player) {
    throw new Error('Missing player object in saveFloorState payload.');
  }
  await openStorage();

  const floorNumber = clampFloor(player.current_floor || 1, player.towerId);
  const slotIndex = player.slotIndex || null;
  const floor = slotIndex
    ? await read(STORES.SLOT_FLOORS, slotFloorKey(slotIndex, floorNumber))
    : await read(STORES.DUNGEON_FLOORS, floorNumber);
  if (!floor) return { success: false };

  floor.chests = Array.isArray(chests) ? chests : floor.chests || [];
  await put(slotIndex ? STORES.SLOT_FLOORS : STORES.DUNGEON_FLOORS, floor);
  return { success: true };
}

